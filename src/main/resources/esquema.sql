CREATE TABLE IF NOT EXISTS obras_sociales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(50) NOT NULL UNIQUE,
    clave VARCHAR(200) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    rol VARCHAR(20) NOT NULL CHECK (rol IN ('Administrador', 'Médico', 'Paciente')),
    matricula VARCHAR(50) UNIQUE,
    especialidad VARCHAR(100),
    honorario DECIMAL(12,2) CHECK (honorario > 0),
    dni VARCHAR(8) UNIQUE,
    telefono VARCHAR(40),
    obra_social_id BIGINT REFERENCES obras_sociales(id)
);
CREATE TABLE IF NOT EXISTS consultorios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    direccion VARCHAR(200) NOT NULL
);
CREATE TABLE IF NOT EXISTS atenciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medico_id BIGINT NOT NULL REFERENCES usuarios(id),
    consultorio_id BIGINT NOT NULL REFERENCES consultorios(id),
    desde DATE NOT NULL,
    hasta DATE NOT NULL,
    CHECK (desde <= hasta)
);
CREATE TABLE IF NOT EXISTS turnos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medico_id BIGINT NOT NULL REFERENCES usuarios(id),
    paciente_id BIGINT NOT NULL REFERENCES usuarios(id),
    consultorio_id BIGINT NOT NULL REFERENCES consultorios(id),
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    monto DECIMAL(12,2) NOT NULL CHECK (monto > 0),
    descuento BOOLEAN NOT NULL,
    UNIQUE (medico_id, fecha, hora),
    UNIQUE (paciente_id, fecha, hora),
    UNIQUE (consultorio_id, fecha, hora)
);
